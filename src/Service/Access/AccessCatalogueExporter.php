declare(strict_types=1);

namespace App\Service\Access;

use Symfony\Component\DependencyInjection\Attribute\Autowire;

/**
 * Builds, writes and checks the generated access files (F239):
 * `docs/reference/access/api-routes.json` and `docs/reference/permissions.md`.
 *
 * The route table needs only the database. The catalogue also needs the
 * frontend's `docs/reference/admin-screens.json`, found under
 * `SELFHELP_FRONTEND_DIR` (default: the sibling `../sh-selfhelp_frontend`).
 * A missing screens file is an error, never a silent skip.
 *
 * @phpstan-import-type AccessRouteTable from AccessCatalogueRenderer
 * @phpstan-import-type AdminScreen from AccessCatalogueRenderer
 */
final class AccessCatalogueExporter
{
    public const ROUTES_FILE = 'docs/reference/access/api-routes.json';
    public const CATALOGUE_FILE = 'docs/reference/permissions.md';
    public const SCREENS_FILE = 'docs/reference/admin-screens.json';
    public const FRONTEND_DIR_ENV = 'SELFHELP_FRONTEND_DIR';

    public function __construct(
        private readonly AccessRouteTableReader $reader,
        private readonly AccessCatalogueRenderer $renderer,
        #[Autowire('%kernel.project_dir%')]
        private readonly string $projectDir,
        #[Autowire('%selfhelp_cms_version_default%')]
        private readonly string $coreVersion,
    ) {
    }

    /**
     * @return AccessRouteTable
     */
    public function readRouteTable(): array
    {
        return $this->reader->read();
    }

    /**
     * @param AccessRouteTable $table
     */
    public function renderRouteTable(array $table): string
    {
        return $this->renderer->renderRouteTableJson($table);
    }

    /**
     * The frontend folder: the explicit override, else the environment
     * variable, else the sibling checkout.
     */
    public function resolveFrontendDir(?string $override = null): string
    {
        if ($override !== null && $override !== '') {
            return rtrim($override, '/\\');
        }
        $env = $_SERVER[self::FRONTEND_DIR_ENV] ?? $_ENV[self::FRONTEND_DIR_ENV] ?? getenv(self::FRONTEND_DIR_ENV);
        if (is_string($env) && $env !== '') {
            return rtrim($env, '/\\');
        }

        return $this->projectDir . '/../sh-selfhelp_frontend';
    }

    public function screensFilePath(string $frontendDir): string
    {
        return $frontendDir . '/' . self::SCREENS_FILE;
    }

    /**
     * @return list<AdminScreen>
     *
     * @throws \RuntimeException when the file is missing or malformed
     */
    public function loadScreens(string $frontendDir): array
    {
        $path = $this->screensFilePath($frontendDir);
        if (!is_file($path)) {
            throw new \RuntimeException(sprintf(
                'Admin screens file not found: %s. Check out sh-selfhelp_frontend there or set %s (it is generated by "npm run access:screens" in the frontend).',
                $path,
                self::FRONTEND_DIR_ENV
            ));
        }
        $content = file_get_contents($path);
        if ($content === false) {
            throw new \RuntimeException(sprintf('Admin screens file cannot be read: %s', $path));
        }

        return $this->renderer->parseScreens($content, $path);
    }

    /**
     * @param AccessRouteTable $table
     * @param list<AdminScreen> $screens
     */
    public function renderCatalogue(array $table, array $screens): string
    {
        return $this->renderer->renderCatalogue($table, $screens, $this->coreVersion);
    }

    /**
     * @param AccessRouteTable $table
     * @param list<AdminScreen> $screens
     * @return list<string>
     */
    public function findUnguardedPermissions(array $table, array $screens): array
    {
        return $this->renderer->findUnguardedPermissions($table, $screens);
    }

    public function absolutePath(string $relative): string
    {
        return $this->projectDir . '/' . $relative;
    }

    /**
     * True when the committed file equals the generated content. Line ends
     * are compared as `\n`, so a Windows checkout with autocrlf passes.
     */
    public function isFresh(string $relative, string $generated): bool
    {
        $path = $this->absolutePath($relative);
        if (!is_file($path)) {
            return false;
        }
        $current = file_get_contents($path);

        return $current !== false && str_replace("\r\n", "\n", $current) === $generated;
    }

    public function write(string $relative, string $content): void
    {
        $path = $this->absolutePath($relative);
        $dir = dirname($path);
        if (!is_dir($dir) && !mkdir($dir, 0775, true) && !is_dir($dir)) {
            throw new \RuntimeException(sprintf('Cannot create directory %s', $dir));
        }
        if (file_put_contents($path, $content) === false) {
            throw new \RuntimeException(sprintf('Cannot write %s', $path));
        }
    }
}
